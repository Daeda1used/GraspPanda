"""Generate one page per method: how to run it in five minutes, and the options of every slot.

``docs/methods/<method>.md`` starts with *Run <method> in five minutes*: where the weights
come from and under which licence, the conversion command and the file it writes, the
demo on the example scene, the same from Python and in the browser, and a test on a
subset of the benchmark, with what each printed when it was measured. The facts come from
the metafile of the method (``configs/<method>/metafile.yaml``: weights, licence,
``convert``, the whole-split rows), from its config (the pipeline and the post-processing)
and from ``docs/methods/five_minutes.json`` (the measured runs: date, commit, machine, wall
time, counts, AP); nothing measured is written into this generator.

Then the page lists, for every slot of the method, what the method ships with, the
options the config check accepts there (the verdict of their probe, the four levels, the
class, the grasps per frame, the fall of every loss term, the command), the options it
refuses (the reason, its kind, the lift) and the options without a record. All of it
comes from :mod:`grasppanda.combine.options`, the module behind ``grasppanda compose
<method config> --list``, so the page, the command and the explorer list the same options.

The slot pages (``docs/slots/``) carry a short generated block between two markers that
links every method's list of that slot and says what a class is; it is written here too.

    python -m tools.make_method_pages           # rewrite
    python -m tools.make_method_pages --check   # exit 1 and name what is stale

``tests/unit/test_method_options.py`` runs the check, so a stale page fails CI;
``tests/unit/test_method_quickstart.py`` runs every command of the five-minute sections
(parsing, a toy detector, or the files a command needs) and holds the measured runs to
the metafiles.
"""

