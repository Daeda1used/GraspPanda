def _docs_tool() -> Any:
    """``tools/make_combination_docs.py``: the table helpers and the level definitions."""
    name = "make_combination_docs"
    if name in sys.modules:
        return sys.modules[name]
    spec = importlib.util.spec_from_file_location(name, Path(__file__).with_name(f"{name}.py"))
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def page_of(method: str) -> str:
    """The stem of a method's page: the directory of its config."""
    return option_lists.methods()[method].split("/")[0]


def anchor(slot: str) -> str:
    return slot.replace("_", "-")


def _code(text: str) -> str:
    return f"`{text}`" if text else "—"


def _levels(entry: option_lists.Entry) -> str:
    if entry.levels is None:
        return "—"
    return " ".join(MARKS.get(entry.levels.states[level], "?") for level in LEVELS)


def _falls(entry: option_lists.Entry) -> str:
    if entry.judge < 2:
        return "not checked"
    parts = [
        f"{term} " + ("never active" if fall is None else f"{fall * 100:.0f} %")
        for term, fall in entry.fall.items()
    ]
    return ", ".join(parts) or "—"


def _why(entry: option_lists.Entry) -> str:
    parts = []
    if entry.verdict in ("runs-unstable", "fails") and entry.reason:
        parts.append(entry.reason)
    if entry.levels is not None:
        parts += [f"{level}: {'; '.join(items)}" for level, items in entry.levels.why.items()]
        parts += entry.levels.notes
    return "; ".join(parts) or "—"


def _name(entry: option_lists.Entry) -> str:
    option = entry.option
    if option.slot == "loss":
        name = "<br>".join(f"`{item}`" for item in option.sets)
    else:
        name = f"`{option.name}`"
    return name + (" (shipped)" if entry.shipped else "")


def _grey_if_empty(entry: option_lists.Entry, text: str) -> str:
    docs = _docs_tool()
    return docs.grey(text) if entry.grasps and not any(entry.grasps) else text


def shipped_text(found: option_lists.SlotListing) -> str:
    """What the method ships with in a slot: the component, and the option that composes
    to the method as shipped."""
    text = found.shipped or "nothing here"
    if found.shipped and " " not in found.shipped:
        text = f"`{found.shipped}`"
    return text + (f" (option `{found.shipped_option}`)" if found.shipped_option else "")


def slot_section(found: option_lists.SlotListing) -> list[str]:
    docs = _docs_tool()
    slot = found.slot
    listing = f"grasppanda compose {found.config} --list {slot}"
    lines = [
        f"## {TITLES.get(slot, slot)} {{#{anchor(slot)}}}",
        "",
        f"Written as `{option_lists.SLOT_KEYS.get(slot, slot)}`; {found.method} ships "
        f"{shipped_text(found)}. The options are explained on the slot page "
        f"[{SLOT_PAGE[slot].replace('_', ' ')}](../slots/{SLOT_PAGE[slot]}.md); the same "
        f"list in a terminal: `{listing}`.",
        "",
    ]
    fits = found.group("fits")
    if fits:
        rows = []
        for entry in fits:
            verdict = VERDICT_MARKS.get(entry.verdict, "") + f" {entry.verdict}"
            if entry.adapter:
                verdict += f" in `{entry.adapter}`"
            grasps = " · ".join(map(str, entry.grasps)) or "—"
            rows.append(
                [
                    _grey_if_empty(entry, _name(entry)) + f"<br>{entry.option.component}",
                    verdict,
                    _levels(entry),
                    _grey_if_empty(entry, grasps),
                    _falls(entry),
                    docs.class_text(entry.classes)
                    if entry.classes
                    else "— (a set of several losses)",
                    _why(entry),
                ]
            )
        headers = [
            "Option",
            "Verdict",
            "C R L P",
            "Grasps per frame",
            "Fall per loss term",
            "Class",
            "What kept it from a level",
        ]
        commands = [entry.command for entry in fits if entry.command]
        lines += [f"### Fit: {len(fits)}", "", *docs._table(headers, rows), ""]
        lines += [
            f'??? note "The compose command of each of the {len(commands)} options that fit"',
            "",
            "    ```bash",
            *[f"    {command}" for command in commands],
            "    ```",
            "",
        ]
    refused = found.group("does not fit")
    if refused:
        rows = []
        for entry in refused:
            kind = entry.kind or "not recorded"
            lifts = "; ".join(part["lift"] for part in entry.refusal if part.get("lift")) or "—"
            classes = docs.class_text(entry.classes) if entry.classes else "—"
            rows.append(
                [_name(entry), _code(entry.option.component), kind, entry.reason, lifts, classes]
            )
        headers = ["Option", "Component", "Kind", "Why it does not fit", "Lift", "Class"]
        lines += [f"### Do not fit: {len(refused)}", "", *docs._table(headers, rows), ""]
    missing = found.group(option_lists.NOT_PROBED)
    if missing:
        rows = [[_name(entry), _code(entry.option.component), entry.reason] for entry in missing]
        lines += [
            f"### Not probed: {len(missing)}",
            "",
            *docs._table(["Option", "Component", "Why there is no record"], rows),
            "",
        ]
    lines += [f"- {note}" for note in found.notes]
    return [*lines, *([""] if found.notes else [])]


