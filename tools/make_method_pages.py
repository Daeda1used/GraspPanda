def slot_block(stem: str) -> list[str]:
    """The generated block of a slot page: the lists of every method, and the caveat."""
    slots = SLOT_PAGE_SLOTS[stem]
    links = []
    for method in option_lists.methods():
        own = [slot for slot in slots if slot in option_lists.method_slots(method)]
        if own:
            targets = ", ".join(
                f"[{TITLES[slot].lower()}](../methods/{page_of(method)}.md#{anchor(slot)})"
                for slot in own
            )
            links.append(f"{method} ({targets})")
    if not links:
        return []
    example = option_lists.methods()[next(iter(option_lists.methods()))]
    return [
        BEGIN,
        "",
        '!!! note "Which of these options fit a method"',
        "",
        "    Every method has a page that lists the options of each of its slots with what "
        "was measured for each (the verdict, the levels *composes*, *runs*, *learns* and "
        "*predicts*, the class, the grasps, the reason of a refusal): "
        + "; ".join(links)
        + f". In a terminal: `grasppanda compose {example} --list {slots[0]}`.",
        "",
        f"    *Class: {CAVEAT}.* Where this page names a class or a measured verdict, it is "
        "one of the [measured classes](../advanced_guides/measured_combinations.md#measured-classes).",
        "",
        END,
    ]


def with_block(text: str, block: list[str]) -> str:
    """A slot page with its generated block replaced, or added after the first heading."""
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    body = "\n".join(block)
    if pattern.search(text):
        return pattern.sub(lambda _: body, text, count=1)
    lines = text.split("\n")
    first = next(index for index, line in enumerate(lines) if line.startswith("# "))
    # After the heading and the paragraph that follows it.
    at = first + 1
    while at < len(lines) and not lines[at].strip():
        at += 1
    while at < len(lines) and lines[at].strip():
        at += 1
    return "\n".join([*lines[:at], "", body, *lines[at:]])


#: The header of a column of a hand-written table of a slot page that holds the class of
#: the option of its row at the level `runs`; the generator writes the class, a note after
#: "; " is kept.
CLASS_HEADER = "Class at *runs*"
_TOKEN = re.compile(r"`([^`]+)`")


def _cells(row: str) -> list[str]:
    """The cells of a row of a Markdown table (an escaped pipe stays in its cell)."""
    return [cell.strip() for cell in re.split(r"(?<!\\)\|", row.strip())[1:-1]]


def with_class_cells(text: str, slots: tuple[str, ...], records: option_lists.Measured) -> str:
    """A slot page whose columns *Class at runs* hold the class of their option today."""
    known = {
        (option.slot, option.name)
        for method in option_lists.methods()
        for option in option_lists.options(method)
        if option.slot in slots
    }

    def option_of(cells: list[str]) -> tuple[str, str] | None:
        for cell in cells:
            for token in _TOKEN.findall(cell):
                slot, _, name = token.partition("=")
                if name and (slot, name) in known:
                    return slot, name
                for candidate in slots:
                    if (candidate, token) in known:
                        return candidate, token
        return None

    lines = text.split("\n")
    column = None
    for index, line in enumerate(lines):
        if not line.startswith("|"):
            column = None
            continue
        cells = _cells(line)
        if CLASS_HEADER in cells:
            column = cells.index(CLASS_HEADER)
            continue
        if column is None or set(line) <= set("|-: "):
            continue
        found = option_of(cells)
        if found is None:
            continue
        note = cells[column].partition("; ")[2]
        runs = option_lists.classes(*found, records)["runs"].text
        cells[column] = runs + (f"; {note}" if note else "")
        lines[index] = "| " + " | ".join(cells) + " |"
    return "\n".join(lines)


def expected() -> dict[Path, str]:
    records = option_lists.Measured.load(MEASURED)
    found = {
        PAGES / f"{page_of(method)}.md": page(method, records) for method in option_lists.methods()
    }
    for stem, slots in SLOT_PAGE_SLOTS.items():
        path = SLOT_PAGES / f"{stem}.md"
        block = slot_block(stem)
        if block and path.is_file():
            text = with_block(path.read_text(encoding="utf-8"), block)
            found[path] = with_class_cells(text, slots, records)
    return found


def stale() -> list[Path]:
    return [
        path
        for path, content in expected().items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n")[0])
    parser.add_argument("--check", action="store_true", help="do not write; exit 1 when stale")
    args = parser.parse_args(argv)
    if args.check:
        outdated = stale()
        for path in outdated:
            print(f"stale: {path.relative_to(REPO)} (run python -m tools.make_method_pages)")
        return 1 if outdated else 0
    PAGES.mkdir(parents=True, exist_ok=True)
    for path, content in expected().items():
        changed = not path.is_file() or path.read_text(encoding="utf-8") != content
        path.write_text(content, encoding="utf-8")
        print(f"{'wrote' if changed else 'unchanged'} {path.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
