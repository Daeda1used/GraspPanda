"""The scale statistic of Scale-Balanced-Grasp: a histogram of grasp widths, as an asset.

Scale-Balanced-Grasp weights the losses of a seed by how rare the width of its best
grasp is among the training labels (:mod:`grasppanda.models.assigners.scale_balance`).
The reference reads the histogram from ``statistic/scale_distribution.npy``, relative to
the working directory, when its loss module is imported; the script that produced the
file is not published.

Here the histogram is a derived asset of the dataset, with a hash and a manifest, and
the dataset attaches it to every training sample. Two sources:

``native``
    Generated by ``grasppanda prepare <dataset> --scale-statistic`` from the training
    frames through the data recipe of the config: for every ``frame_step``-th frame the
    seeds the backbone would keep are matched to labels, and the width of the best
    grasp over all views is collected for the *graspable* seeds (on an object, more than
    ``min_graspable_views`` views with a score target above ``graspable_score``). The
    histogram has ``bins`` equal bins between the smallest and the largest width
    collected. This population is an inference: among the candidates tried it is the
    one whose distribution has the shape of the reference file (see the method README);
    the counts of that file are not reproduced.
``legacy_import``
    The reference's own file, imported with ``--import-legacy --scale-statistic-file``.
    It is marked ``legacy-import`` because its generator is unknown, and is meant for
    parity work and for training with exactly the reference's weights.
"""

from __future__ import annotations

import hashlib
import io
import os
import pickle
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Any, Literal

import numpy as np

from .assets import Asset, AssetError, AssetSpec, save_arrays

__all__ = ["ScaleStatisticConfig", "ScaleStatisticStore", "read_reference_statistic"]

_FILE = "histogram.npz"


@dataclass(frozen=True)
class ScaleStatisticConfig:
    """Which width histogram a dataset serves.

    Attributes:
        source: ``native`` or ``legacy_import``, see the module docstring.
        bins: Number of equal-width bins. The reference file has 32.
        frame_step: ``native``: every ``frame_step``-th frame of the split is used.
        num_seeds: ``native``: seeds per frame, the furthest-point subsample the
            backbone keeps.
        min_graspable_views, graspable_score: ``native``: a seed is counted when more
            than this many of its views have a score target above ``graspable_score``.
        max_width: ``native``: a grasp wider than this is not usable (the gripper's).
        seed: ``native``: seed of the dataset's sampling, so that the result is a fixed
            function of the configuration.
        reference_sha256: ``legacy_import``: SHA-256 of the reference file that is meant.
            The import refuses any other file.
    """

    source: Literal["native", "legacy_import"]
    bins: int = 32
    reference_sha256: str | None = None
    frame_step: int = 8
    num_seeds: int = 1024
    min_graspable_views: int = 10
    graspable_score: float = 0.1
    max_width: float = 0.1
    seed: int = 0

    def problems(self) -> list[str]:
        found = []
        if self.source not in ("native", "legacy_import"):
            found.append(
                f"`scale_statistic.source` must be native or legacy_import, got {self.source!r}."
            )
        if self.bins < 1 or self.frame_step < 1 or self.num_seeds < 1:
            found.append("`scale_statistic` needs bins, frame_step and num_seeds of at least 1.")
        if self.source == "legacy_import" and len(self.reference_sha256 or "") != 64:
            found.append(
                "`scale_statistic.reference_sha256` (64 hex digits) is required for "
                "source: legacy_import; it says which reference file is meant."
            )
        if self.source == "native" and self.reference_sha256 is not None:
            found.append("`scale_statistic.reference_sha256` belongs to source: legacy_import.")
        return found

    def parameters(self) -> dict[str, Any]:
        """What decides the content of the histogram, for the asset hash."""
        if self.source == "legacy_import":
            return {"bins": self.bins, "reference_sha256": self.reference_sha256}
        parameters = asdict(self)
        del parameters["source"], parameters["reference_sha256"]
        return parameters


class _ArraysOnly(pickle.Unpickler):
    """Unpickles NumPy arrays inside plain containers and nothing else."""

    _ALLOWED = frozenset(
        {
            ("numpy.core.multiarray", "_reconstruct"),
            ("numpy._core.multiarray", "_reconstruct"),
            ("numpy.core.multiarray", "scalar"),
            ("numpy._core.multiarray", "scalar"),
            ("numpy", "ndarray"),
            ("numpy", "dtype"),
            ("_codecs", "encode"),  # how pickle protocol 2 spells the bytes of an array
        }
    )

    def find_class(self, module: str, name: str) -> Any:
        if (module, name) not in self._ALLOWED:
            raise pickle.UnpicklingError(f"refusing to load {module}.{name}")
        return super().find_class(module, name)


def read_reference_statistic(path: str | os.PathLike[str]) -> tuple[np.ndarray, np.ndarray]:
    """``(edges, counts)`` from a file in the reference's format.

    The format is a pickled mapping ``{"num": counts, "interval": edges}`` saved with
    ``numpy.save``. It is read without executing arbitrary pickled code: anything but
    NumPy arrays in plain containers is refused.
    """
    path = Path(path)
    with path.open("rb") as handle:
        try:
            version = np.lib.format.read_magic(handle)
            if version == (1, 0):
                _, _, dtype = np.lib.format.read_array_header_1_0(handle)
            else:
                _, _, dtype = np.lib.format.read_array_header_2_0(handle)
            if not dtype.hasobject:
                raise ValueError("not an object array")
            content = _ArraysOnly(io.BytesIO(handle.read())).load()
            content = content.item() if isinstance(content, np.ndarray) else content
            counts = np.asarray(content["num"], dtype=np.int64)
            edges = np.asarray(content["interval"], dtype=np.float64)
        except (ValueError, KeyError, TypeError, IndexError, pickle.UnpicklingError) as error:
            raise AssetError(
                f"{path} is not a scale statistic in the reference's format (a saved mapping "
                f"with 'num' and 'interval'): {error}"
            ) from error
    _check(edges, counts, str(path))
    return edges, counts


def _check(edges: np.ndarray, counts: np.ndarray, where: str) -> None:
    if (
        edges.ndim != 1
        or counts.ndim != 1
        or len(edges) != len(counts) + 1
        or not (np.diff(edges) > 0).all()
        or not (counts > 0).all()
    ):
        raise AssetError(
            f"{where}: a scale histogram needs K + 1 increasing edges and K positive counts, got "
            f"{edges.shape} edges and {counts.shape} counts (an empty bin has no finite weight; "
            "use fewer bins or more frames)"
        )


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


class ScaleStatisticStore:
    """The width histogram of one dataset configuration, in the asset store.

    Args:
        dataset: Dataset name.
        config: Which histogram; part of the asset hash.
        inputs: What identifies the data a native histogram is computed from: the
            grasp-label store, split, camera, preprocessing and transform configs.
        root: Asset root; defaults to :func:`grasppanda.utils.paths.cache_root`.
    """

    KIND = "scale_statistic"
    GENERATOR = "grasppanda.scale_statistic"
    VERSION = 1

    def __init__(
        self,
        dataset: str,
        config: ScaleStatisticConfig,
        inputs: dict[str, Any],
        root: str | os.PathLike[str] | None = None,
    ) -> None:
        self.config = config
        native = config.source == "native"
        spec = AssetSpec(
            dataset=dataset,
            kind=self.KIND,
            generator=self.GENERATOR if native else "unknown (reference file)",
            version=self.VERSION,
            parameters=config.parameters(),
            inputs=inputs if native else {"dataset": dataset},
            uses_ground_truth=native,  # seeds on objects are found with the ground-truth mask
            provenance="native" if native else "legacy-import",
            about={
                "edges": "(K + 1,) float64 bin edges of the grasp width, metres",
                "counts": "(K,) int64 seeds whose best grasp has a width in the bin",
            },
        )
        self.asset = Asset(spec, root)
        self._loaded: tuple[np.ndarray, np.ndarray] | None = None

    @property
    def file(self) -> Path:
        return self.asset.path / _FILE

    def save(self, edges: np.ndarray, counts: np.ndarray, **record: Any) -> None:
        """Store a histogram and mark the asset complete."""
        edges, counts = np.asarray(edges, np.float64), np.asarray(counts, np.int64)
        _check(edges, counts, "the generated histogram")
        if len(counts) != self.config.bins:
            raise AssetError(
                f"the histogram has {len(counts)} bins, but the configuration asks for "
                f"{self.config.bins}"
            )
        self.asset.create()
        save_arrays(self.file, {"edges": edges, "counts": counts})
        self.asset.mark_complete("histogram", total=int(counts.sum()), **record)
        self._loaded = None

    def import_reference(self, path: str | os.PathLike[str]) -> None:
        """Import a file in the reference's format (``legacy_import`` only)."""
        if self.config.source != "legacy_import":
            raise AssetError("only a legacy_import statistic can be imported from a file")
        digest = _sha256(Path(path))
        if digest != self.config.reference_sha256:
            raise AssetError(
                f"{path} has SHA-256 {digest}, but the configuration names the reference file "
                f"{self.config.reference_sha256}"
            )
        edges, counts = read_reference_statistic(path)
        self.save(edges, counts, source_file=Path(path).name)

    def exists(self) -> bool:
        return self.asset.exists() and self.asset.is_complete("histogram")

    def require(self, *, build: str) -> None:
        self.asset.require(["histogram"], build=build)

    def load(self) -> tuple[np.ndarray, np.ndarray]:
        """``(edges, counts)``; raises :class:`AssetError` if the asset is not built."""
        if self._loaded is None:
            if not self.exists():
                raise AssetError(f"the scale statistic at {self.asset.path} has not been built")
            with np.load(self.file) as archive:
                self._loaded = (archive["edges"], archive["counts"])
        return self._loaded
