def generate_graspness(
    dataset: SceneReader,
    maps: GraspnessMaps,
    scene: int,
    config: GraspnessConfig,
    workers: int = 1,
    progress: Callable[[SampleKey], None] | None = None,
) -> dict[str, int]:
    """Generate and write the maps of one scene; the object-level part runs once.

    Returns:
        The shard record (frames written, points labelled) for
        :meth:`GraspnessMaps.mark_complete`, which the caller invokes.
    """
    labels = dataset.scene_labels(scene)
    values = [object_graspness(instance, config.friction_threshold) for instance in labels]
    if config.normalization == "instance":
        values = [instance_normalised(value) for value in values]
    keys = dataset.scene_keys(scene)
    record = {"frames": len(keys), "points": 0}

    def frames() -> Iterator[tuple[int, np.ndarray]]:
        for key in keys:
            frame = dataset.frame(key)
            poses = dataset.object_poses(key, config.poses)
            array = frame_graspness(frame, poses, labels, values, config.dtype, workers)
            record["points"] += int(np.count_nonzero(frame.valid))
            yield key.frame, array
            if progress is not None:
                progress(key)

    maps.write_scene(scene, frames(), len(keys))
    return record


def import_legacy_graspness(
    dataset: SceneReader,
    maps: GraspnessMaps,
    scene: int,
    legacy: LegacyGraspness,
    dtype: str,
    progress: Callable[[SampleKey], None] | None = None,
) -> dict[str, int]:
    """Re-key a scene's upstream-format files to pixels, asserting every row count.

    Returns:
        The shard record for :meth:`GraspnessMaps.mark_complete`, which the caller invokes.
    """
    keys = dataset.scene_keys(scene)
    record = {"frames": len(keys), "points": 0}

    def frames() -> Iterator[tuple[int, np.ndarray]]:
        for key in keys:
            _, valid = dataset.frame(key).require_cloud("legacy graspness import")
            pixels = np.flatnonzero(valid)
            out = np.full(valid.shape, np.nan, dtype=dtype)
            out.reshape(-1)[pixels] = legacy.read(key, pixels, valid.shape)
            record["points"] += len(pixels)
            yield key.frame, out
            if progress is not None:
                progress(key)

    maps.write_scene(scene, frames(), len(keys))
    return record
