"""Point-wise graspness: generation, pixel-keyed storage and the legacy reader.

Definition (Graspness reference generator):

1. Per annotated grasp point of an object, the fraction of its grid of grasps that is
   usable in the scene: friction score in ``(0, threshold]`` and not colliding.
2. Every point of the preprocessed scene cloud takes the value of the nearest annotated
   point of any object. There is no distance limit, so table and background points get a
   value too.
3. The values of a frame are min-max normalised over that frame's point set.

With ``normalization: instance`` (FineGrasp's instance-normalised graspness) the values
of step 1 are first min-max normalised within every object instance, so that the best
point of each object reaches 1 before step 2 spreads the values and step 3 normalises
the frame. A small object whose best point is poor by the standards of its neighbours
is then no longer pushed below the selection threshold. The parameter is part of the
asset's identity, so the two variants are separate assets that any graspness-supervised
method can be trained on.

Step 3 makes the values depend on the preprocessing mask, and the reference stores them
as one array per frame in the row order of the masked cloud, with no key. A different
crop margin, mask rule or camera then misaligns every label without an error. Here the
values are stored **per pixel** (``NaN`` outside the generation mask), the asset is
looked up by a hash that contains the preprocessing fingerprint, and a reader refuses a
frame whose mask differs from the one the map was generated for.

The nearest-neighbour step reproduces the reference arithmetic (squared distances
accumulated in single precision, lowest index on ties) without its quadratic cost: a
k-d tree answers every query whose two nearest neighbours are clearly separated, and
only the remaining near-ties are decided by the single-precision brute force.
"""

