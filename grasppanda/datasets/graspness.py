class GraspnessMaps:
    """Pixel-keyed graspness maps in the asset store: one compressed archive per scene.

    Args:
        asset: The asset directory, native or legacy-import.
    """

    KIND = "graspness"

    def __init__(self, asset: Asset) -> None:
        self.asset = asset

    @staticmethod
    def spec(
        dataset: str,
        camera: str,
        config: GraspnessConfig,
        preprocessing: Sequence[dict[str, Any]],
        uses_ground_truth: bool,
        label_hash: str,
    ) -> AssetSpec:
        """Identity of the asset a dataset configuration asks for."""
        per_instance = config.normalization == "instance"
        about = {
            "values": "graspness in [0, 1], min-max normalised per frame over the mask"
            + (", after a min-max normalisation within every object instance" * per_instance),
            "layout": "scene_<id>.npz, one (H, W) array per frame named by frame id",
            "key": "pixel; NaN outside the preprocessing mask the map was generated for",
        }
        if config.source == "legacy_import":
            return AssetSpec(
                dataset=dataset,
                kind=GraspnessMaps.KIND,
                generator="legacy-import",
                version=1,
                parameters={"camera": camera, "dtype": config.dtype},
                inputs={"dataset": dataset},
                preprocessing=preprocessing,
                uses_ground_truth=uses_ground_truth,
                provenance="legacy-import",
                about=about,
            )
        parameters = {
            "camera": camera,
            "friction_threshold": float(config.friction_threshold),
            "poses": config.poses,
            "dtype": config.dtype,
            "neighbour": "nearest, float32 squared distance, lowest index on ties",
            "normalisation": "per-frame min-max over the mask",
        }
        if per_instance:
            # Added only for the variant: the identity, and with it the hash, of every
            # scene-normalised asset generated before the parameter existed is unchanged.
            parameters["instance_normalisation"] = (
                "min-max over the annotated points of each object instance, 0 for a "
                "constant instance, before the nearest-neighbour step"
            )
        return AssetSpec(
            dataset=dataset,
            kind=GraspnessMaps.KIND,
            generator="grasppanda.graspness",
            version=1,
            parameters=parameters,
            inputs={"dataset": dataset, "grasp_labels": label_hash},
            preprocessing=preprocessing,
            uses_ground_truth=uses_ground_truth,
            about=about,
        )

    def shard_file(self, scene: int) -> Path:
        return self.asset.path / f"{scene_shard(scene)}.npz"

    def write_scene(self, scene: int, maps: Iterable[tuple[int, np.ndarray]], frames: int) -> None:
        """Write a scene's archive atomically from ``(frame, map)`` pairs.

        The shard is not marked complete: several processes may write scenes at once,
        and only the one that owns the manifest calls :meth:`mark_complete`.
        """
        count = 0
        with (
            atomic_path(self.shard_file(scene)) as temporary,
            zipfile.ZipFile(temporary, "w", zipfile.ZIP_DEFLATED) as archive,
        ):
            for frame, array in maps:
                with archive.open(f"{frame:04d}.npy", "w", force_zip64=True) as member:
                    np.lib.format.write_array(member, array, allow_pickle=False)
                count += 1
            if count != frames:
                raise AssetError(f"scene {scene}: wrote {count} maps, expected {frames}")

    def mark_complete(self, scene: int, record: dict[str, int]) -> None:
        """Record a written scene, with what its generation reported, in the manifest."""
        file = self.shard_file(scene)
        if not file.is_file():
            raise AssetError(f"cannot mark scene {scene} complete: {file} is missing")
        self.asset.mark_complete(scene_shard(scene), **record, bytes=file.stat().st_size)

    def read_map(self, key: SampleKey) -> np.ndarray:
        """The stored ``(H, W)`` map of a frame."""
        if not self.asset.is_complete(scene_shard(key.scene)):
            raise AssetError(
                f"graspness of {key} is not in the asset at {self.asset.path}: scene "
                f"{key.scene} has not been generated"
            )
        with np.load(self.shard_file(key.scene)) as archive:
            name = f"{key.frame:04d}"
            if name not in archive.files:
                raise AssetError(f"{self.shard_file(key.scene)} has no map for frame {key.frame}")
            return archive[name]

    def read(self, key: SampleKey, pixels: np.ndarray, image_size: tuple[int, int]) -> np.ndarray:
        stored = self.read_map(key)
        if stored.shape != tuple(image_size):
            raise AssetError(
                f"graspness map of {key} is {stored.shape}, but the frame is {tuple(image_size)}"
            )
        flat = stored.reshape(-1)
        labelled = np.flatnonzero(~np.isnan(flat))
        if not np.array_equal(labelled, pixels):
            raise AssetError(
                f"graspness map of {key} was generated for a different mask: it labels "
                f"{len(labelled)} pixels, the frame's preprocessing keeps {len(pixels)}"
                + ("" if len(labelled) != len(pixels) else " (same count, different pixels)")
                + f". Asset: {self.asset.path}. The dataset content or the preprocessing code "
                "changed since generation; rebuild the asset."
            )
        return flat[pixels].astype(np.float32)

    def record(self) -> dict[str, Any]:
        return self.asset.record()


class LegacyGraspness:
    """Reader of upstream-format graspness files, with a per-frame alignment check.

    Upstream files hold one ``(M, 1)`` array per frame, row-aligned to the masked cloud
    of the preprocessing they were generated with. Nothing in the file says which
    preprocessing that was; the only check available is the row count, and it is made
    for every frame served.

    Args:
        path: Maps a frame to its file.
        fingerprint: Preprocessing fingerprint of the dataset, for error messages.
    """

    def __init__(self, path: Callable[[SampleKey], Path], fingerprint: str) -> None:
        self.path = path
        self.fingerprint = fingerprint

    def read(self, key: SampleKey, pixels: np.ndarray, image_size: tuple[int, int]) -> np.ndarray:
        file = self.path(key)
        if not file.is_file():
            raise AssetError(f"no legacy graspness file for {key}: {file}")
        values = np.load(file)
        if values.ndim == 2 and values.shape[1] == 1:
            values = values[:, 0]
        if values.ndim != 1 or len(values) != len(pixels):
            raise AssetError(
                f"legacy graspness of {key} does not align with this dataset's preprocessing: "
                f"{file} has shape {values.shape}, but the masked cloud has {len(pixels)} points "
                f"(preprocessing fingerprint {self.fingerprint}). Upstream files are row-aligned "
                "to cloud[depth > 0 & workspace mask] of the pipeline that generated them. Use "
                "that preprocessing, or generate a native asset: grasppanda prepare <dataset> "
                "--graspness"
            )
        if not np.isfinite(values).all():
            raise AssetError(
                f"legacy graspness of {key} contains NaN or Inf ({file}); upstream normalises "
                "without an epsilon, so a frame whose values are all equal is undefined"
            )
        return values.astype(np.float32)

    def record(self) -> dict[str, Any]:
        return {
            "kind": "graspness",
            "provenance": "legacy",
            "generator": "unknown",
            "alignment": "row count checked per frame",
            "preprocessing_fingerprint": self.fingerprint,
        }


