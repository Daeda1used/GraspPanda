#: Query points whose two nearest label points differ by less than this are re-decided
#: in single precision. The band is far wider than the rounding of float32 coordinates
#: (a few 1e-7 m per metre of range), so outside it double and single precision agree.
_TIE_RELATIVE = 1e-5
_TIE_ABSOLUTE = 4e-6


@dataclass(frozen=True)
class GraspnessConfig:
    """Which point-wise graspness a dataset serves.

    Attributes:
        source: ``native`` reads the pixel-keyed asset generated by ``grasppanda prepare``;
            ``legacy_import`` reads a pixel-keyed asset imported from upstream-format
            files; ``legacy`` reads upstream-format files directly, verifying the row
            count of every frame. The two legacy sources are for parity work: their
            generator is unknown.
        friction_threshold: A grasp counts when its friction score is in
            ``(0, friction_threshold]``. The reference uses 0.8. Required for the native
            source, where it is a parameter of the asset; it has no default because the
            generator, not this reader, owns the value.
        poses: Which of the dataset's object poses place the annotated points. For
            GraspNet-1Billion the reference generator reads the per-frame ``annotations``
            (XML, rounded to four decimals) while training labels use ``meta``. Required
            for the native source.
        dtype: Storage type of the pixel-keyed maps.
        normalization: ``scene`` (GSNet, EconomicGrasp) normalises the values of a frame
            once, over its point set. ``instance`` (FineGrasp) first normalises the
            values of every object instance over that object's annotated points, see
            :func:`instance_normalised`. A parameter of the native asset; the generator
            of legacy files is unknown.
    """

    source: Literal["native", "legacy_import", "legacy"]
    friction_threshold: float | None = None
    poses: str | None = None
    dtype: Literal["float16", "float32"] = "float16"
    normalization: Literal["scene", "instance"] = "scene"

    def problems(self, pose_sources: Sequence[str]) -> list[str]:
        """What is missing or invalid for a dataset that offers ``pose_sources``."""
        if self.normalization not in ("scene", "instance"):
            return [
                f"`graspness.normalization` must be 'scene' or 'instance', got "
                f"{self.normalization!r}."
            ]
        if self.source != "native":
            if self.normalization != "scene":
                return [
                    "`graspness.normalization` is a parameter of the native generator; a "
                    f"'{self.source}' source serves files as they are. Remove it or use "
                    "`source: native`."
                ]
            return []
        found = []
        if self.friction_threshold is None:
            found.append(
                "`graspness.friction_threshold` is required for the native source "
                "(the Graspness reference uses 0.8)."
            )
        if self.poses not in pose_sources:
            found.append(
                f"`graspness.poses` must be one of {', '.join(pose_sources)} for the native "
                f"source, got {self.poses!r}."
            )
        return found


class GraspnessSource(Protocol):
    """Anything that can provide the graspness of a frame's masked cloud."""

    def read(self, key: SampleKey, pixels: np.ndarray, image_size: tuple[int, int]) -> np.ndarray:
        """``(M,)`` float32 values of the points at ``pixels`` (the full masked cloud)."""

    def record(self) -> dict[str, Any]:
        """Summary for run records, including the provenance of the labels."""


class SceneReader(Protocol):
    """What the generator needs from a dataset."""

    name: str
    camera: str

    def scene_keys(self, scene: int) -> list[SampleKey]:
        """Every frame of a scene for the dataset's camera."""

    def frame(self, key: SampleKey) -> Frame:
        """The preprocessed frame: organised cloud and validity mask."""

    def object_poses(self, key: SampleKey, source: str) -> list[tuple[int, np.ndarray]]:
        """``(object_id, pose)`` of every instance, in the order of the collision labels."""

    def scene_labels(self, scene: int) -> list[StoredGraspLabels]:
        """Grasp labels of every instance of a scene, in the same order."""


def scene_shard(scene: int) -> str:
    return f"scene_{scene:06d}"


# -------------------------------------------------------------------------- definition


def object_graspness(labels: StoredGraspLabels, friction_threshold: float) -> np.ndarray:
    """Fraction of usable grasps at every annotated point of an object instance.

    Returns:
        ``(P,)`` float64 in ``[0, 1]``.
    """
    threshold = np.float32(friction_threshold)  # scores are float32; compare in kind
    counts = np.empty(labels.num_points, dtype=np.int64)
    for start in range(0, labels.num_points, 256):
        rows = slice(start, start + 256)
        scores = np.asarray(labels.scores[rows])
        usable = (scores > 0) & (scores <= threshold) & ~labels.collision(rows)
        counts[rows] = usable.reshape(len(scores), -1).sum(axis=1)
    return counts / labels.grid.size


def instance_normalised(values: np.ndarray) -> np.ndarray:
    """Min-max normalise the graspness of one object instance over its annotated points.

    ``(g - min) / (max - min)``, so the best point of every object has the value 1 and
    its worst 0. An object whose points all have the same value (in practice: no usable
    grasp anywhere in this scene) has no best point; it keeps 0 everywhere. The label
    generator published with FineGrasp divides by zero there, which turns the whole
    frame into NaN.

    Returns:
        ``(P,)`` float64 in ``[0, 1]``.
    """
    values = np.asarray(values, dtype=np.float64)
    if values.size == 0:
        return values.copy()
    low, high = values.min(), values.max()
    if not high > low:
        return np.zeros_like(values)
    return (values - low) / (high - low)


def _brute_force_float32(query: np.ndarray, reference: np.ndarray, rows: int = 512) -> np.ndarray:
    """Index of the nearest reference point in float32 arithmetic, lowest index on ties."""
    query = query.astype(np.float32)
    reference = reference.astype(np.float32)
    nearest = np.empty(len(query), dtype=np.int64)
    for start in range(0, len(query), rows):
        block = query[start : start + rows]
        delta = block[:, None, 0] - reference[None, :, 0]
        squared = delta * delta
        for axis in (1, 2):
            delta = block[:, None, axis] - reference[None, :, axis]
            squared += delta * delta
        nearest[start : start + rows] = squared.argmin(axis=1)
    return nearest


def nearest_label_point(query: np.ndarray, reference: np.ndarray, workers: int = 1) -> np.ndarray:
    """For each query point, the index of its nearest reference point.

    Equivalent to an exhaustive search on float32 copies of both arrays with squared
    distances summed in x, y, z order and the lowest index winning ties, which is what
    the reference generator's GPU kernel computes.

    Args:
        query: ``(M, 3)`` float64.
        reference: ``(L, 3)`` float64.
        workers: Threads for the tree query; ``-1`` uses all cores.
    """
    from scipy.spatial import cKDTree

    if len(reference) == 0:
        raise ValueError("nearest_label_point needs at least one reference point")
    if len(reference) == 1:
        return np.zeros(len(query), dtype=np.int64)
    distance, index = cKDTree(reference).query(query, k=2, workers=workers)
    nearest = index[:, 0].astype(np.int64)
    close = distance[:, 1] <= distance[:, 0] * (1.0 + _TIE_RELATIVE) + _TIE_ABSOLUTE
    if close.any():
        nearest[close] = _brute_force_float32(query[close], reference)
    return nearest


def frame_graspness(
    frame: Frame,
    poses: Sequence[tuple[int, np.ndarray]],
    labels: Sequence[StoredGraspLabels],
    values: Sequence[np.ndarray],
    dtype: str,
    workers: int = 1,
) -> np.ndarray:
    """The pixel-keyed graspness map of one frame.

    Args:
        frame: The preprocessed frame.
        poses: ``(object_id, pose)`` of every object instance.
        labels: Grasp labels of the instances, in the same order.
        values: :func:`object_graspness` of each instance.
        dtype: Type of the returned map; values are computed in double precision.
        workers: Threads for the nearest-neighbour query.

    Returns:
        ``(H, W)`` array, ``NaN`` outside the frame's validity mask.
    """
    cloud, valid = frame.require_cloud("graspness generation")
    if len(poses) != len(labels):
        raise AssetError(
            f"{frame.key}: {len(poses)} object poses for {len(labels)} labelled instances"
        )
    placed = [transform_points(instance.points, pose) for (_, pose), instance in zip(poses, labels)]
    pixels = np.flatnonzero(valid)
    if len(pixels) == 0:
        raise AssetError(f"{frame.key}: no pixel survives preprocessing; nothing to label")
    nearest = nearest_label_point(cloud.reshape(-1, 3)[pixels], np.concatenate(placed), workers)
    raw = np.concatenate(values)[nearest]
    low, high = raw.min(), raw.max()
    if not high > low:
        raise AssetError(
            f"{frame.key}: every point has graspness {low}; the per-frame min-max "
            "normalisation is undefined"
        )
    out = np.full(valid.shape, np.nan, dtype=dtype)
    out.reshape(-1)[pixels] = (raw - low) / (high - low)
    return out


