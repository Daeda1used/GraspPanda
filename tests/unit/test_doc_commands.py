"""Every ``grasppanda compose`` command a hand-written page shows does what the page says.

The READMEs, the hand-written pages of ``docs/`` (a page whose header says it is generated
is left to its generator, and so is a block marked ``<!-- name:begin (generated ...) -->``)
and the config READMEs show compose commands in code blocks and in running text. Each
distinct command is run here through the compose API, in process:

* a request (``<base> --set ...``) must be accepted, unless the page shows it refused:
  its output is shown with it (``$ grasppanda compose ...`` followed by the lines compose
  printed, or "output of `...`:" followed by a block) and that output has a ``✗`` line,
  or the command carries the comment ``# refused``; then compose must refuse it (by the
  contract rules or the config check, or as a request it cannot compose);
* a listing (``--list``, ``--show``) must exit 0;
* with ``-o FILE`` the file is written to a scratch directory, where a later command of
  the same page may compose from it, as a reader following the page would.

A command with a placeholder (``<method config>``, ``...``, a shell variable) is skipped;
so is a mention of the command without arguments.
"""

from __future__ import annotations

import re
import shlex
from dataclasses import dataclass, field
from pathlib import Path

import pytest

from grasppanda.cli.main import build_parser, main
from grasppanda.combine.compose import ComposeError, Composition, compose
from grasppanda.config import ConfigError

from .conftest import REPO

FENCE = re.compile(r"^(\s*)(`{3,}|~{3,})")
#: A code span (one or two backticks) that starts with the command; no blank line inside.
INLINE = re.compile(
    r"(?<!`)(`{1,2})(?!`)\s*(grasppanda compose\b(?:(?!\1)(?!\n[ \t]*\n).)*?)\s*\1(?!`)", re.S
)
GENERATED_FILE = re.compile(r"\A\s*<!--\s*Generated by", re.I)
GENERATED_BLOCK = re.compile(
    r"<!--\s*(?P<name>[\w-]+):begin[^>]*generated[^>]*-->.*?<!--\s*(?P=name):end\s*-->",
    re.S | re.I,
)


@dataclass
class Command:
    """One compose command as a page shows it."""

    text: str  # the command, on one line, without a prompt or a trailing comment
    where: str  # page:line of its first appearance
    refused: bool  # the page shows it refused
    before: list[str] = field(default_factory=list)  # earlier commands that write its base


def pages() -> list[Path]:
    found = sorted(REPO.glob("README*.md"))
    found += sorted((REPO / "docs").rglob("*.md"))
    found += sorted((REPO / "configs").rglob("README.md"))
    return [path for path in found if not GENERATED_FILE.match(path.read_text(encoding="utf-8"))]


def _shows_a_refusal(output: list[str]) -> bool:
    return any(line.strip().startswith("✗") for line in output)


def _commented_refused(command: str) -> bool:
    comment = command.partition(" #")[2]
    return "refused" in comment.lower()


def _clean(command: str) -> str:
    """One line: continuations joined, the trailing comment dropped (quotes respected)."""
    joined = re.sub(r"\\\s*\n\s*", " ", command.strip())
    joined = " ".join(joined.split())
    tokens = shlex.split(joined, comments=True)
    return shlex.join(tokens)


def commands_of(path: Path) -> list[tuple[str, int, bool]]:
    """``(command, line, shown refused)`` of every compose command of a page, in order."""
    text = GENERATED_BLOCK.sub(lambda m: "\n" * m.group(0).count("\n"), path.read_text("utf-8"))
    lines = text.splitlines()
    found: list[tuple[int, str, bool]] = []
    prose: list[str] = []  # the page with its code blocks blanked, for the inline commands
    blocks: dict[int, list[str]] = {}  # first line of a block → its lines
    index = 0
    while index < len(lines):
        opening = FENCE.match(lines[index])
        if not opening:
            prose.append(lines[index])
            index += 1
            continue
        fence, start = opening.group(2), index
        body = []
        index += 1
        while index < len(lines) and not lines[index].strip().startswith(fence):
            body.append(lines[index])
            index += 1
        index += 1  # the closing fence
        prose.extend([""] * (index - start))
        blocks[start] = body
        for at, line in enumerate(body):
            stripped = line.strip()
            prompted = stripped.startswith("$ ")
            stripped = stripped.removeprefix("$ ")
            if not stripped.startswith("grasppanda compose"):
                continue
            command, end = stripped, at
            while command.rstrip().endswith("\\") and end + 1 < len(body):
                end += 1
                command = command.rstrip() + "\n" + body[end].strip()
            output = []
            if prompted:  # what compose printed, up to the next prompt
                for line_after in body[end + 1 :]:
                    if line_after.strip().startswith("$ "):
                        break
                    output.append(line_after)
            refused = _commented_refused(command) or _shows_a_refusal(output)
            found.append((start + 2 + at, command, refused))
    text = "\n".join(prose)
    for match in INLINE.finditer(text):
        line = text.count("\n", 0, match.start()) + 1
        command = match.group(2)
        rest = text[match.end() : text.find("\n", match.end())].strip()
        refused = _commented_refused(command)
        if rest.endswith(":"):  # "output of `...`:" and the block that follows it
            following = [start for start in blocks if start >= line]
            if following and min(following) - line <= 2:
                refused = refused or _shows_a_refusal(blocks[min(following)])
        found.append((line, command, refused))
    found.sort()
    return [(command, line, refused) for line, command, refused in found]


def collect() -> tuple[list[Command], list[str]]:
    """The distinct commands of every hand-written page, and the skipped ones."""
    distinct: dict[tuple[str, tuple[str, ...], bool], Command] = {}
    skipped: list[str] = []
    for path in pages():
        relative = path.relative_to(REPO).as_posix()
        writers: dict[str, str] = {}  # file written with -o on this page → its command
        for raw, line, refused in commands_of(path):
            if re.search(r"<[^>]*>|\.\.\.|…|\$\{?\w", raw):  # placeholders, shell variables
                skipped.append(f"{relative}:{line}")
                continue
            text = _clean(raw)
            tokens = shlex.split(text)[2:]
            listing = "--list" in tokens or "--show" in tokens
            if not tokens or (tokens[0].startswith("-") and not listing):
                continue  # the command named, or a flag shown without a base config
            before: list[str] = []
            base = tokens[0] if tokens and not tokens[0].startswith("-") else ""
            while base in writers and writers[base] not in before:  # a file written earlier
                before.insert(0, writers[base])
                base = shlex.split(writers[base])[2]
            command = Command(text, f"{relative}:{line}", refused, before)
            distinct.setdefault((text, tuple(before), refused), command)
            if "-o" in tokens:
                writers[tokens[tokens.index("-o") + 1]] = text
            elif "--output" in tokens:
                writers[tokens[tokens.index("--output") + 1]] = text
    return list(distinct.values()), skipped


COMMANDS, SKIPPED = collect()


@dataclass
class Outcome:
    """What compose made of a command: a composition, a wrong request, or an exit status."""

    result: Composition | None = None
    wrong: str = ""  # the message of a request compose cannot even compose
    status: int | None = None  # of a listing


def run(command: str, directory: Path, where: str) -> Outcome:
    tokens = shlex.split(command)[1:]  # "compose ..."
    try:
        args = build_parser().parse_args(tokens)
    except SystemExit:
        pytest.fail(f"{where}: `{command}` is not a valid command line", pytrace=False)
    if args.list_presets or args.show:
        return Outcome(status=main(tokens))
    base = args.base
    if (directory / base).is_file():
        base = str(directory / base)
    elif (REPO / base).is_file():
        base = str(REPO / base)
    try:
        result = compose(base, args.sets, args.opts, adapters=args.adapters, unsets=args.unsets)
    except (ComposeError, ConfigError) as error:
        return Outcome(wrong=str(error))
    if result.accepted and args.output:
        target = directory / Path(args.output).name
        target.write_text(result.text(target), encoding="utf-8")
    return Outcome(result=result)


def test_the_pages_show_compose_commands():
    assert len(COMMANDS) >= 10, [command.where for command in COMMANDS]
    assert any(" --set " in command.text for command in COMMANDS)
    assert any(command.refused for command in COMMANDS)


@pytest.mark.parametrize("command", COMMANDS, ids=[command.where for command in COMMANDS])
def test_a_compose_command_of_a_page_does_what_the_page_shows(command, tmp_path, capsys):
    for earlier in command.before:
        outcome = run(earlier, tmp_path, command.where)
        assert outcome.result is not None and outcome.result.accepted, (earlier, outcome)
    outcome = run(command.text, tmp_path, command.where)
    capsys.readouterr()
    if outcome.status is not None:
        assert outcome.status == 0, f"`{command.text}` exits {outcome.status} ({command.where})"
        return
    result = outcome.result
    if command.refused:  # by the contract rules, the config check, or as a wrong request
        assert outcome.wrong or not result.accepted, (
            f"{command.where} shows `{command.text}` refused, but compose accepts it now: "
            "show what compose does today"
        )
        assert outcome.wrong or result.refusal(), command.text
        return
    assert not outcome.wrong, f"{command.where}: `{command.text}` is wrong: {outcome.wrong}"
    assert result.accepted, (
        f"{command.where}: `{command.text}` is refused: {result.refusal()}. Fix the command, "
        "or show the refusal (its output with the ✗ line, or a `# refused` comment)."
    )
