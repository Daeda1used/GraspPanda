"""Backbones compared with the official implementations they claim to reproduce.

``tools/make_backbone_fixtures.py`` ran each official implementation on one fixed scene
and stored a sample of its output in ``fixtures/backbones/``. Here the GraspPanda
backbone runs on the same scene and has to agree.

Two kinds of evidence:

* **Released weights.** The official checkpoint is loaded strictly (no missing and no
  unexpected key) and the outputs are compared. Needs the checkpoint on disk:
  ``GRASPPANDA_WEIGHTS`` names a directory laid out as the paths below; the test is
  skipped when a file is absent and fails when its SHA-256 is not the recorded one.
* **Analytic weights.** Both sides fill their state dict with the same closed-form
  values, so no file is needed. This covers options no released checkpoint uses and
  proves that the two state dicts have identical keys and shapes.

Outputs are compared in strict float32: on recent GPUs cuDNN otherwise computes
convolutions in TF32, which alone moves PointNet++ features by about 5e-3.
"""

from __future__ import annotations

import hashlib
import importlib.util
import json
import os
import pickle
import zlib
from pathlib import Path

import numpy as np
import pytest
import torch
from torch import nn

from grasppanda.ops import serialization_code
from grasppanda.registry import BACKBONES
from grasppanda.structures import PointSet
from grasppanda.utils.paths import cache_root

pytestmark = pytest.mark.oracle

FIXTURES = Path(__file__).parent / "fixtures" / "backbones"
HAS_SPCONV = importlib.util.find_spec("spconv") is not None
needs_spconv = pytest.mark.skipif(not HAS_SPCONV, reason="needs the spconv extra")

#: Largest absolute feature difference accepted against an oracle. Measured values are
#: listed in docs/model_zoo_backbones.md; the largest is 2.1e-5 on features of magnitude 3.
TOLERANCE = 1e-4

#: Fixture name -> backbone, released checkpoint below ``$GRASPPANDA_WEIGHTS``.
RELEASED = {
    "ptv3_scannet": ("PTv3", "components/scannet-semseg-pt-v3m1-0-base.pth"),
    "concerto_tiny": ("PTv3Sonata", "components/concerto_tiny.pth"),
    "concerto_small": ("PTv3Sonata", "components/concerto_small.pth"),
    "concerto_base": ("PTv3Sonata", "components/concerto_base.pth"),
    "concerto_large": ("PTv3Sonata", "components/concerto_large.pth"),
    "utonia": ("PTv3Utonia", "components/utonia.pth"),
}
ANALYTIC = {
    "ptv3_analytic": "PTv3",
    "sonata_analytic": "PTv3Sonata",
    "concerto_analytic": "PTv3Sonata",
    "utonia_analytic": "PTv3Utonia",
}


# -------------------------------------------------------------------------- helpers


def fixture(name: str) -> dict[str, np.ndarray]:
    """Load a recorded reference.

    References computed from permissively licensed or analytic weights are committed.
    Those computed from non-commercial weights (GraspNet-baseline, Concerto, Utonia) are
    kept out of the repository, under ``$GRASPPANDA_CACHE/fixtures/backbones``, and are
    regenerated by ``tools/make_backbone_fixtures.py``.
    """
    for directory in (FIXTURES, cache_root() / "fixtures" / "backbones"):
        path = directory / f"{name}.npz"
        if path.is_file():
            return dict(np.load(path))
    pytest.skip(f"fixture {name}.npz has not been recorded")


def released(relative: str, sha256: str) -> Path:
    root = os.environ.get("GRASPPANDA_WEIGHTS", "")
    path = Path(root) / relative
    if not root or not path.is_file():
        pytest.skip(f"needs $GRASPPANDA_WEIGHTS/{relative}")
    digest = hashlib.sha256()
    with open(path, "rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    assert digest.hexdigest() == sha256, f"{path} is not the file the fixture was recorded with"
    return path


def load_checkpoint(path: Path) -> dict:
    """Unpickle without running code; training checkpoints need a few named globals."""
    try:
        return torch.load(path, map_location="cpu", weights_only=True)
    except pickle.UnpicklingError:
        from torch.optim.lr_scheduler import OneCycleLR

        scalar = (getattr(np, "_core", None) or np.core).multiarray.scalar
        allowed = [
            getattr,
            np.dtype,
            OneCycleLR,
            type(np.dtype("f8")),
            (scalar, "numpy.core.multiarray.scalar"),
        ]
        with torch.serialization.safe_globals(allowed):
            return torch.load(path, map_location="cpu", weights_only=True)


def analytic_state(model: nn.Module) -> None:
    """The same closed-form state dict the fixture recorder gives the official model."""
    state = model.state_dict()
    for name, tensor in state.items():
        leaf = name.rsplit(".", 1)[-1]
        if not tensor.is_floating_point() or leaf == "inv_freq":
            continue
        phase = zlib.crc32(name.encode()) % 1000
        wave = torch.sin(torch.arange(tensor.numel(), dtype=torch.float64) * 0.37 + phase)
        if leaf == "running_var":
            values = 1.0 + 0.5 * wave.pow(2)
        elif leaf == "running_mean":
            values = 0.1 * wave
        elif tensor.ndim >= 2:
            values = wave * (1.5 / (tensor.numel() // tensor.shape[0]) ** 0.5)
        elif leaf in ("weight", "gamma"):
            values = 1.0 + 0.1 * wave
        else:
            values = 0.1 * wave
        state[name] = values.reshape(tensor.shape).to(tensor.dtype)
    model.load_state_dict(state)


def state_keys(model: nn.Module) -> str:
    lines = sorted(f"{key} {tuple(value.shape)}" for key, value in model.state_dict().items())
    return hashlib.sha256("\n".join(lines).encode()).hexdigest()


def point_features(cloud: torch.Tensor, channels: int) -> torch.Tensor:
    """Monomials of the coordinates in float32: bit-identical to the recorder's NumPy."""
    x, y, z = (cloud - torch.tensor([0.0, 0.0, 0.5])).unbind(-1)
    monomials = [x, y, z, x * y, y * z, z * x, x * x, y * y, z * z, x * y * z, x * x * y, y * y * z]
    return torch.stack([monomials[index % 12] * 4.0 for index in range(channels)], dim=1)


@pytest.fixture(scope="module")
def scene() -> torch.Tensor:
    return torch.from_numpy(fixture("tabletop")["cloud"])


@pytest.fixture(params=["cpu", "cuda"])
def device(request) -> torch.device:
    if request.param == "cuda" and not torch.cuda.is_available():
        pytest.skip("needs a CUDA device")
    return torch.device(request.param)


@pytest.fixture(autouse=True)
def strict_float32():
    saved = torch.backends.cudnn.allow_tf32, torch.backends.cuda.matmul.allow_tf32
    torch.backends.cudnn.allow_tf32 = torch.backends.cuda.matmul.allow_tf32 = False
    yield
    torch.backends.cudnn.allow_tf32, torch.backends.cuda.matmul.allow_tf32 = saved


def dense_output(
    model: nn.Module, scene: torch.Tensor, device: torch.device, with_feats: bool = True
) -> np.ndarray:
    model = model.to(device).eval()
    feats = point_features(scene, model.in_channels).to(device) if with_feats else None
    with torch.no_grad():
        return model(PointSet(scene.to(device)), feats).feats.cpu().numpy()


def assert_matches(out: np.ndarray, recorded: dict[str, np.ndarray], tolerance: float) -> None:
    rows = recorded["feature_rows"]
    assert np.abs(recorded["features"]).max() > 0.1, "a fixture of zeros proves nothing"
    assert np.abs(out[rows] - recorded["features"]).max() < tolerance
    # Statistics over every row guard the rows that were not stored.
    assert np.abs(out.mean(0) - recorded["feature_mean"]).max() < tolerance
    assert np.abs(out.std(0) - recorded["feature_std"]).max() < tolerance


# ---------------------------------------------------------------------------- tests


def test_serialisation_codes_equal_the_official_ones():
    recorded = fixture("serialization")
    for depth in (1, 3, 7, 10, 16):
        grid = torch.from_numpy(recorded[f"grid_{depth}"])
        batch = torch.from_numpy(recorded[f"batch_{depth}"])
        for order in ("z", "z-trans", "hilbert", "hilbert-trans"):
            expected = torch.from_numpy(recorded[f"code_{depth}_{order}"])
            assert torch.equal(serialization_code(grid, depth, order, batch), expected)


def test_pointnet2_reproduces_graspnet_baseline_with_its_released_weights(scene, device):
    recorded = fixture("pointnet2_graspnet")
    path = released("graspnet_baseline/checkpoint-rs.tar", str(recorded["weights_sha256"]))
    prefix = "view_estimator.backbone."
    checkpoint = load_checkpoint(path)["model_state_dict"]
    state = {key[len(prefix) :]: value for key, value in checkpoint.items() if prefix in key}

    model = BACKBONES.build({"type": "PointNet2"})
    model.load_state_dict(state, strict=True)
    assert sum(p.numel() for p in model.parameters()) == int(recorded["parameters"]) == 641_856

    model = model.to(device).eval()
    with torch.no_grad():
        out = model(PointSet(scene.to(device)))
    # The same 1024 seeds in the same order, then the same features on them.
    assert np.array_equal(out.points.parent_index.cpu().numpy(), recorded["seed_index"])
    assert np.array_equal(out.points.coords.cpu().numpy(), recorded["seed_xyz"])
    assert_matches(out.feats.cpu().numpy(), recorded, TOLERANCE)


@needs_spconv
@pytest.mark.parametrize("name", sorted(RELEASED))
def test_ptv3_family_reproduces_released_weights(name, scene, device):
    kind, relative = RELEASED[name]
    recorded = fixture(name)
    path = released(relative, str(recorded["weights_sha256"]))
    config = json.loads(str(recorded["config"]))
    model = BACKBONES.build({"type": kind, **config, "grid_size": float(recorded["grid_size"])})
    state = load_checkpoint(path)["state_dict"]
    if kind == "PTv3":  # a Pointcept segmentor checkpoint: backbone plus head
        prefix = next(p for p in ("module.backbone.", "backbone.") if any(p in k for k in state))
        state = {key[len(prefix) :]: value for key, value in state.items() if prefix in key}
    model.load_state_dict(state, strict=True)
    assert sum(p.numel() for p in model.parameters()) == int(recorded["parameters"])
    assert_matches(dense_output(model, scene, device), recorded, TOLERANCE)


@needs_spconv
@pytest.mark.parametrize("name", sorted(ANALYTIC))
def test_ptv3_family_matches_the_official_code_with_analytic_weights(name, scene, device):
    recorded = fixture(name)
    config = json.loads(str(recorded["config"]))
    kind = ANALYTIC[name]
    model = BACKBONES.build({"type": kind, **config, "grid_size": float(recorded["grid_size"])})
    assert state_keys(model) == str(recorded["state_keys"]), "state dict layout differs"
    assert sum(p.numel() for p in model.parameters()) == int(recorded["parameters"])
    analytic_state(model)
    assert_matches(dense_output(model, scene, device), recorded, TOLERANCE)


@pytest.mark.slow  # 20 000 points through the pure-PyTorch operators: about 20 s on a CPU
@pytest.mark.parametrize(
    ("name", "parameters"), [("pointnext_s", 790_720), ("pointnext_b", 3_826_336)]
)
def test_pointnext_matches_the_official_code_with_analytic_weights(name, parameters, scene, device):
    recorded = fixture(name)
    model = BACKBONES.build({"type": "PointNeXt", **json.loads(str(recorded["config"]))})
    assert state_keys(model) == str(recorded["state_keys"]), "state dict layout differs"
    assert sum(p.numel() for p in model.parameters()) == int(recorded["parameters"]) == parameters
    analytic_state(model)
    assert_matches(dense_output(model, scene, device), recorded, 1e-5)
